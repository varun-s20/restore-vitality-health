"""Restore Vitality Health: Jinja globals for photos and product cut-outs.

Reads data/photos.json (written by tools/photos_make.py, product photos by tools/products_make.py) and data/products.json. Both globals read ROOT and
the page language L from the template context.
  {{ photo('hero', '100vw', cls='hero__img', lazy=False) }}
  {{ product_img(p.slug, cls='card__img') }}
"""
import json
import os

from jinja2 import pass_context
from markupsafe import Markup, escape

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(os.path.dirname(HERE), 'data')

with open(os.path.join(DATA, 'photos.json'), encoding='utf-8') as f:
    PHOTOS = json.load(f)
with open(os.path.join(DATA, 'products.json'), encoding='utf-8') as f:
    PRODUCT_DATA = {p['slug']: p for p in json.load(f)}


def _srcset(root, pattern, files):
    return ', '.join('%s%s %dw' % (root, pattern % w, w) for w, _ in files)


@pass_context
def photo(ctx, slot, sizes, cls='', lazy=True, alt=None):
    root, lang = ctx['ROOT'], ctx['L']
    p = PHOTOS['photos'][slot]
    w, h = p['files'][-1]
    pattern = 'assets/images/photo/' + slot + '-%d.webp'
    if alt is None:
        alt = p['alt_es'] if lang == 'es' else p['alt_en']
    load = 'loading="lazy"' if lazy else 'fetchpriority="high"'
    img = ('<img src="%s%s" srcset="%s" sizes="%s" width="%d" height="%d" alt="%s"%s %s decoding="async" '
           'data-slot="%s">') % (
        root, pattern % w, _srcset(root, pattern, p['files']), escape(sizes), w, h, escape(alt),
        ' class="%s"' % escape(cls) if cls else '', load, escape(slot))
    phone = PHOTOS['photos'].get(slot + '-phone')
    if not phone:
        return Markup(img)
    ppattern = 'assets/images/photo/' + slot + '-phone-%d.webp'
    pw, ph = phone['files'][-1]
    source = '<source media="(max-width: 640px)" srcset="%s" sizes="100vw" width="%d" height="%d" data-slot="%s-phone">' % (
        _srcset(root, ppattern, phone['files']), pw, ph, escape(slot))
    return Markup('<picture>%s%s</picture>' % (source, img))


CUTOUT_SIZES = '(max-width: 640px) 60vw, 280px'
PHOTO_SIZES = '(max-width: 640px) 80vw, 400px'


@pass_context
def product_img(ctx, slug, cls='', lazy=True, sizes=CUTOUT_SIZES):
    """Product image. Entries marked "photo" (tools/products_make.py) are 4:5 packshots: they get class
    is-photo, and when sizes is left at its default they use PHOTO_SIZES instead."""
    root, lang = ctx['ROOT'], ctx['L']
    entry = PHOTOS['products'][slug]
    files = entry['files']
    if entry.get('photo'):
        cls = (cls + ' is-photo').strip()
        if sizes == CUTOUT_SIZES:
            sizes = PHOTO_SIZES
    w, h = files[-1]
    prod = PRODUCT_DATA[slug]
    name = prod.get(lang, {}).get('name') or prod['name']
    pattern = 'assets/images/products/rvh-product-' + slug + '-%d.webp'
    load = 'loading="lazy"' if lazy else 'fetchpriority="high"'
    return Markup('<img src="%s%s" srcset="%s" sizes="%s" width="%d" height="%d" alt="%s"%s %s decoding="async">' % (
        root, pattern % w, _srcset(root, pattern, files), escape(sizes), w, h, escape(name),
        ' class="%s"' % escape(cls) if cls else '', load))


def write_focus_css():
    """Object positions per slot, as CSS (check.py allows no inline styles). Phone crops use the phone entry's focus."""
    rules = ['/* Generated by tools/photos.py from data/photos.json: object-position per photo slot. Do not edit. */']
    for slot, p in sorted(PHOTOS['photos'].items()):
        if slot.endswith('-phone'):
            continue
        rules.append('img[data-slot="%s"] { object-position: %s; }' % (slot, p['focus']))
        phone = PHOTOS['photos'].get(slot + '-phone')
        if phone:
            rules.append('@media (max-width: 640px) { img[data-slot="%s"] { object-position: %s; } }' % (slot, phone['focus']))
    with open(os.path.join(os.path.dirname(HERE), 'assets', 'photo-focus.css'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(rules) + '\n')


write_focus_css()
