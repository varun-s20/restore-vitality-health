from markupsafe import Markup, escape

import art  # tools/art.py: the drawn media system (upgrade pass 8b)

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.dirname(HERE)
PROJECT = os.path.dirname(SITE)
SRC = os.path.join(SITE, 'src')
SITE_URL = 'https://restorevitality.health'  # unconfirmed: brief.md open question 2. Change here only.
LANGS = ('en', 'es')
GENERATED = '<!-- Generated by tools/build.py from src/{src}. Edit that file, not this one. -->'
MACROS = ('lang_switch', 'button', 'text_link', 'img', 'safety', 'card', 'cred', 'closing', 'quiz_row',
          'faq_items', 'faq', 'banner', 'intro', 'newsletter')
IMPORT = '{%% from "partials/macros.html" import %s with context %%}' % ', '.join(MACROS)


def load(name):
    with open(os.path.join(SITE, 'data', name), encoding='utf-8') as f:
        return json.load(f)


SITE_STR = load('site.json')
PRODUCTS = load('products.json')
for _cat in ('mens', 'womens', 'shared'):  # card compositions take turns along each rail (tools/art.py)
    art.ORDER.update({p['slug']: i for i, p in enumerate(q for q in PRODUCTS if q['category'] == _cat)})
MEDIA = load('media.json')


# ---- copy deck readers (word for word) ----
def deck(lang):
    name = 'copy.md' if lang == 'en' else 'copy-es.md'
    with open(os.path.join(PROJECT, 'content', name), encoding='utf-8') as f:
        return f.read()


def deck_section(lang, page, sub):
    text = deck(lang)
    part = text.split('\n## ' + page + '\n', 1)[1].split('\n## ', 1)[0]
    return part.split('\n### ' + sub + '\n', 1)[1].split('\n### ', 1)[0]


QA_RE = re.compile(r'^\s*- \*\*(.+?)\*\* (.+)$')


def qa_pairs(block):
    return [list(m.groups()) for m in (QA_RE.match(l) for l in block.split('\n')) if m]


def faq_themes(lang):
    """The FAQ page's four themes, in deck order: [[theme, [[q, a], ...]], ...]."""
    block = deck_section(lang, 'FAQ (page)', 'FAQ')
    names = {'en': ['Getting started', 'Prescriptions and safety', 'Billing', 'Privacy'],
             'es': ['Primeros pasos', 'Recetas y seguridad', 'Pagos', 'Privacidad']}[lang]
    chunks = re.split(r'\n\*\*(?:Getting started|Prescriptions and safety|Billing|Privacy)\*\*\n', block)[1:]
    return [[n, qa_pairs(c)] for n, c in zip(names, chunks)]


def category_faq(lang, page):
    return qa_pairs(deck_section(lang, page, 'FAQ'))


CATEGORY_PAGE = {'mens': "Men's health (category page)", 'womens': "Women's health (category page)",
                 'shared': 'Shared treatments (category page)'}


def faq_heading(lang, page):
    block = deck_section(lang, page, 'FAQ')
    return re.search(r'- Heading: (.+)', block).group(1).strip()


# ---- jinja ----
def hl(value):
    """Headline weights: **words** become <strong>, set in the 600 weight by CSS."""
    s = str(escape(value))
    return Markup(re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', s))


def linkify(value):
    s = str(escape(value))
    s = s.replace('support@rx.restorevitality.health',
                  '<a class="a-inline" href="mailto:support@rx.restorevitality.health">support@rx.restorevitality.health</a>')
    return Markup(s)


env = Environment(loader=FileSystemLoader(SRC), autoescape=True, undefined=StrictUndefined,
                  trim_blocks=False, lstrip_blocks=False, keep_trailing_newline=True)
env.filters['hl'] = hl
env.filters['linkify'] = linkify
env.globals.update(step_art=art.step_art, product_art=art.product_art, program_art=art.program_art,
                   quiz_art=art.quiz_art)
import photos  # tools/photos.py: stock photos and product cut-outs (R2); writes assets/photo-focus.css
env.globals.update(photo=photos.photo, product_img=photos.product_img)


def render(source, ctx):
    return env.from_string(IMPORT + source).render(**ctx)


META_RE = re.compile(r'^\s*<!--\s*meta\s*\n(.*?)-->\s*\n', re.S)


def split_meta(source, src_name):
    m = META_RE.match(source)
    if not m:
        raise SystemExit('missing meta block: ' + src_name)
    meta = {}
    for line in m.group(1).strip().split('\n'):
        k, _, v = line.partition(':')
        meta[k.strip()] = v.strip()
    for k in ('title', 'description'):
        if not meta.get(k):
            raise SystemExit('missing %s in %s' % (k, src_name))
    return meta, source[m.end():]


def by_cat(cat):
    return [p for p in PRODUCTS if p['category'] == cat]


def context(lang, page):
    return {
        'S': SITE_STR[lang], 'L': lang, 'ROOT': '' if lang == 'en' else '../', 'page': page,
        'media': MEDIA, 'products': PRODUCTS, 'by_cat': by_cat, 'SITE_URL': SITE_URL,
        'faq_themes': faq_themes(lang), 'category_faq': lambda c: category_faq(lang, CATEGORY_PAGE[c]),
        'category_faq_heading': lambda c: faq_heading(lang, CATEGORY_PAGE[c]),
        'product': lambda slug: next(p for p in PRODUCTS if p['slug'] == slug),
    }


def assemble(lang, page, meta, body_html, src_name, schema=None):
    ctx = context(lang, page)
    url_path = page if lang == 'en' else 'es/' + page
    if page == 'index.html':
        url_path = '' if lang == 'en' else 'es/'
    meta = dict({'og_title': '', 'og_description': '', 'preload': '', 'noindex': ''}, **meta)
    ctx.update(meta=meta, url_path=url_path, en_path='' if page == 'index.html' else page, schema=schema)
    head = render(read('partials/head.html'), ctx)
    head = head.replace('<head>', '<head>\n' + GENERATED.format(src=src_name), 1)
    return head + render(read('partials/header.html'), ctx) + '\n<main id="main">\n' + body_html.strip() + \
        '\n</main>\n\n' + render(read('partials/footer.html'), ctx)


def read(rel):
    with open(os.path.join(SRC, rel), encoding='utf-8') as f:
        return f.read()


def schema_for(page, lang, meta):
    org = {'@type': 'Organization', '@id': SITE_URL + '/#organization', 'name': 'Restore Vitality Health',
           'url': SITE_URL + '/', 'email': 'support@rx.restorevitality.health',
           'logo': SITE_URL + '/assets/icons/rvh-og-mark.png'}
    graph = [org] if page == 'index.html' else []
    graph.append({'@type': 'WebPage', 'name': meta['title'], 'description': meta['description'],
                  'inLanguage': lang, 'isPartOf': {'@id': SITE_URL + '/#organization'}})
    return json.dumps({'@context': 'https://schema.org', '@graph': graph}, ensure_ascii=False)


# ---- pages ----
def build_all():
    out = {}
    # hand-written pages
    for lang in LANGS:
        folder = os.path.join(SRC, 'pages') if lang == 'en' else os.path.join(SRC, 'pages', 'es')
        for fn in sorted(os.listdir(folder)):
            if not fn.endswith('.body.html'):
                continue
            slug = fn[:-len('.body.html')]
            page = slug + '.html'
            rel = 'pages/' + fn if lang == 'en' else 'pages/es/' + fn
            meta, body = split_meta(read(rel), rel)
            body_html = render(body, dict(context(lang, page), meta=meta))
            out[(lang, page)] = assemble(lang, page, meta, body_html, rel, schema_for(page, lang, meta))

    # treatment pages
    tpl = read('templates/treatment.body.html')
    for p in PRODUCTS:
        page = p['slug'] + '.html'
        for lang in LANGS:
            t = p[lang]
            tail = {'en': 'Prescribed online by a licensed provider in your state.',
                    'es': 'Recetado en línea por un profesional con licencia en su estado.'}[lang]
            meta = {'title': '%s | Restore Vitality Health' % p['name'],
                    'description': '%s %s %s. %s' % (t['card'], t['price'], t['period'], tail),
                    }
            ctx = dict(context(lang, page), p=p, t=t, meta=meta)
            body_html = render(tpl, ctx)
            schema = json.dumps({'@context': 'https://schema.org', '@type': 'Drug', 'name': p['name'],
                                 'description': t['card'], 'prescriptionStatus': 'https://schema.org/PrescriptionOnly',
                                 'activeIngredient': ', '.join(t['ingredients'])}, ensure_ascii=False)
            out[(lang, page)] = assemble(lang, page, meta, body_html, 'templates/treatment.body.html', schema)

    # legal pages
    tpl = read('templates/legal.body.html')
    for L in legal_pages():
        page = L['slug'] + '.html'
        for lang in LANGS:
            meta = {'title': '%s | Restore Vitality Health' % L['names'][lang], 'description': L['desc'][lang]}
            ctx = dict(context(lang, page), Lp=L, meta=meta)
            out[(lang, page)] = assemble(lang, page, meta, render(tpl, ctx), 'templates/legal.body.html',
                                         schema_for(page, lang, meta))
    return out


