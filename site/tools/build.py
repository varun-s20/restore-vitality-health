def legal_pages():
    """Client text verbatim from assets/legal/existing-site-legal.md, between each page's ```text fences.
    The first line is the H1. Short lines without closing punctuation are section headings; everything else
    is a paragraph. Words are never changed."""
    with open(os.path.join(PROJECT, 'assets', 'legal', 'existing-site-legal.md'), encoding='utf-8') as f:
        src = f.read()
    pages = []
    for slug, h1, es_name, en_desc, es_desc in LEGAL:
        part = src.split('\n## /%s\n' % slug, 1)[1]
        text = part.split('```text\n', 1)[1].split('\n```', 1)[0]
        lines = [l.strip() for l in text.split('\n')]
        assert lines[0] == h1, (slug, lines[0])
        blocks = []
        for l in lines[1:]:
            if not l:
                continue
            is_head = len(l) <= 70 and not re.search(r'[.:;,)]$', l) and not l.startswith('Last modified')
            kind = 'h' if is_head else 'p'
            if l == 'Opt-Out Now':
                kind = 'optout'
            blocks.append((kind, l))
        pages.append({'slug': slug, 'h1': h1, 'blocks': blocks, 'names': {'en': h1, 'es': es_name},
                      'desc': {'en': en_desc, 'es': es_desc}})
    return pages


def write_all(check=False):
    out = build_all()
    stale = []
    for (lang, page), html in sorted(out.items()):
        path = os.path.join(SITE, page) if lang == 'en' else os.path.join(SITE, 'es', page)
        html = re.sub(r'[ \t]+\n', '\n', html)
        html = re.sub(r'\n{3,}', '\n\n', html)
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old != html:
            stale.append(path)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, 'w', encoding='utf-8', newline='\n') as f:
                    f.write(html)
    # sitemap and robots
    urls = []
    for (lang, page) in sorted(out):
        if page == '404.html':
            continue
        p = '' if page == 'index.html' else page
        urls.append(SITE_URL + '/' + ('' if lang == 'en' else 'es/') + p)
    sm = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + \
        ''.join('  <url><loc>%s</loc></url>\n' % u for u in urls) + '</urlset>\n'
    robots = 'User-agent: *\nAllow: /\n\nSitemap: %s/sitemap.xml\n' % SITE_URL
    for name, content in (('sitemap.xml', sm), ('robots.txt', robots)):
        path = os.path.join(SITE, name)
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old != content:
            stale.append(path)
            if not check:
                with open(path, 'w', encoding='utf-8', newline='\n') as f:
                    f.write(content)
    if check:
        if stale:
            print('stale:', *stale, sep='\n  ')
            sys.exit(1)
        print('up to date')
    else:
        print('%d pages, %d written' % (len(out), len(stale)))


if __name__ == '__main__':
    write_all(check='--check' in sys.argv)
