"""Restore Vitality Health: page build.

Assembles every page as head + header + body + footer from src/, in English at the site root and in Spanish
under es/ with the same file names. Templates are Jinja (already installed with Python here).
- src/pages/<slug>.body.html and src/pages/es/<slug>.body.html: one source per page and language. Each opens
  with a meta comment (title, description, preload, schema, og_title, og_description, noindex).
- src/templates/treatment.body.html: the 21 treatment pages, from data/products.json.
- src/templates/legal.body.html: the 5 legal pages, from the client's verbatim text in ../assets/legal/.
- FAQ answers are read from the copy decks (content/copy.md, copy-es.md) word for word.
Also writes sitemap.xml and robots.txt.

Run from the project folder or site/:  python site/tools/build.py        (write)
                                        python site/tools/build.py --check (fail if any output is stale)
"""
